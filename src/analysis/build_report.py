"""Facts sheet from the run logs and result files: settings, software versions, dataset
sizes, permutation results and the AUROC-by-k table. Writes results/facts_for_draft.md.
"""
import glob
import json

import numpy as np
import pandas as pd

from metabo import config
from metabo.stats import bh as _bh


def _read_jsonl(path):
    out = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if line:
                out.append(json.loads(line))
    return out


def _load_events():
    events = []
    for f in glob.glob(str(config.RESULTS_DIR / "runlog_*.jsonl")):
        events += _read_jsonl(f)
    return events


def _load_results(kind):
    rows = []
    for f in glob.glob(str(config.RESULTS_DIR / f"{kind}_*.json")):
        rows += json.load(open(f))
    df = pd.DataFrame(rows)
    if not df.empty and "target" in df.columns:
        df = df[df["target"].isin(config.OUTCOMES)].reset_index(drop=True)
    return df


def _dedupe_perm(pm):
    """Keep the record with the most permutations per pair; fail on true duplicates."""
    if pm.empty or "key" not in pm.columns or "n_perm" not in pm.columns:
        return pm
    top = pm[pm["n_perm"] == pm.groupby("key")["n_perm"].transform("max")]
    if top["key"].duplicated().any():
        dups = list(top.loc[top["key"].duplicated(keep=False), "key"].unique()[:5])
        raise SystemExit(f"duplicate permutation records at the same n_perm for "
                         f"{dups}; clean the results folder first.")
    dropped = len(pm) - len(top)
    if dropped:
        print(f"dropped {dropped} permutation records with fewer permutations")
    return top.reset_index(drop=True)


def main():
    events = _load_events()
    ev = _load_results("eval")
    pm = _dedupe_perm(_load_results("permutation"))
    out = config.RESULTS_DIR / "facts_for_draft.md"
    L = ["# Facts sheet\n", "Generated by analysis/build_report.py from the run logs and results.\n"]

    starts = [e for e in events if e.get("kind") == "run_start"]
    if starts:
        last = starts[-1]
        prov = last.get("provenance", {})
        ver = prov.get("versions", {})
        s = last.get("settings", {})
        L += ["## Settings",
              f"- git: `{prov.get('git')}`  host: `{prov.get('host')}`  "
              f"python: {prov.get('python')}",
              f"- versions: " + ", ".join(f"{k} {v}" for k, v in ver.items() if v),
              f"- seed: {s.get('SEED')}; nested CV: outer {s.get('OUTER_K')} x "
              f"inner {s.get('INNER_K')}; bootstrap: {s.get('N_BOOTSTRAP')}; "
              f"permutations: {s.get('N_PERMUTATION')}",
              f"- representations: {s.get('REPRESENTATIONS')}; dims: "
              f"{s.get('EMBED_DIMS')}; models: {s.get('MODELS')}",
              f"- UMAP n_neighbors={s.get('UMAP_N_NEIGHBORS')}, "
              f"min_dist={s.get('UMAP_MIN_DIST')}; VAE max_epochs="
              f"{s.get('VAE_MAX_EPOCHS')}, patience={s.get('VAE_PATIENCE')}, "
              f"val_fraction={s.get('VAE_VAL_FRACTION')}; min events="
              f"{s.get('MIN_EVENTS')}\n"]

    tps = {e["timepoint"]: e for e in events if e.get("kind") == "timepoint_loaded"}
    if tps:
        L += ["## Dataset", "", "| Timepoint | Subjects | Metabolites |",
              "|---|---|---|"]
        for tp, e in tps.items():
            L.append(f"| {tp} | {e['n_subjects']} | {e['n_metabolites']} |")
        L.append("")
    targ = pd.DataFrame([e for e in events if e.get("kind") == "target"])
    if not targ.empty:
        targ = targ.drop_duplicates(["timepoint", "target"])
        L += [f"- Outcomes per timepoint (>= {config.MIN_EVENTS} events): "
              + ", ".join(f"{tp}: {n}" for tp, n in
                          targ.groupby('timepoint').size().items()),
              f"- Outcome prevalence range: {100*targ.prevalence.min():.0f}%"
              f"-{100*targ.prevalence.max():.0f}%; "
              f"events-per-metabolite (EPV) range: {targ.epv.min():.3f}"
              f"-{targ.epv.max():.3f}\n"]

    if not pm.empty:
        # BH within each timepoint (14 outcomes), NOT the manuscript's BH over all 42 pairs
        # (that one is pair_statistics.py's q_bh42 / build_table_s1.py's raw_perm_q_bh42).
        pm["q_value"] = pm.groupby("timepoint")["p_value"].transform(
            lambda s: _bh(s.values))
        pm["predictive"] = pm["p_value"] < 0.05
        pm["fdr_sig"] = pm["q_value"] < 0.05
        npred = int(pm["predictive"].sum())
        nfdr = int(pm["fdr_sig"].sum())
        qmin = pm["q_value"].min()
        L += ["## RQ1, permutation test on the raw metabolome",
              f"- {npred}/{len(pm)} pairs at p < 0.05",
              f"- {nfdr}/{len(pm)} at q < 0.05 (BH within timepoint); smallest q = {qmin:.3f}",
              "- pairs at p < 0.05:"]
        for _, r in pm[pm.predictive].sort_values("p_value").iterrows():
            L.append(f"  - {r['timepoint']} / {r['target']}: "
                     f"AUROC={r['obs_auroc']:.3f}, p={r['p_value']:.3f}, "
                     f"q={r['q_value']:.3f} (n={r['n']}, events={r['n_events']})")
        ctrl = pm[pm["target"].isin(["fishoil", "vitd"])]
        if not ctrl.empty:
            L.append("- trial arms (fish oil, vitamin D):")
            for _, r in ctrl.iterrows():
                L.append(f"  - {r['timepoint']} / {r['target']}: "
                         f"AUROC={r['obs_auroc']:.3f}, p={r['p_value']:.3f}")
        L.append("")

    if not ev.empty and not pm.empty:
        predictive = set(map(tuple, pm.loc[pm.predictive, ["timepoint", "target"]].values))
        ev["pred"] = ev.apply(lambda r: (r.timepoint, r.target) in predictive, axis=1)
        bydim = (ev.sort_values("auroc", ascending=False)
                   .groupby(["timepoint", "target", "representation", "dim"]).head(1))
        sub = bydim[bydim["pred"]]
        # best of three classifiers per cell for raw and embeddings alike
        raw_ref = sub.loc[sub.representation == "raw", "auroc"].mean()
        L += ["## RQ2, mean AUROC by k over the pairs with p < 0.05",
              f"- raw: {raw_ref:.3f}"]
        curve = sub[sub.representation != "raw"].pivot_table(
            index="dim", columns="representation", values="auroc", aggfunc="mean")
        if not curve.empty:
            L.append("")
            L.append("| dim | " + " | ".join(curve.columns) + " |")
            L.append("|---|" + "---|" * len(curve.columns))
            for dim, row in curve.iterrows():
                L.append(f"| {dim} | " + " | ".join(
                    f"{row[c]:.3f}" if pd.notna(row[c]) else "-" for c in curve.columns) + " |")
        L.append("")

    with open(out, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {out}  ({len(events)} log events, "
          f"{len(ev)} eval, {len(pm)} permutation records)")


if __name__ == "__main__":
    main()
